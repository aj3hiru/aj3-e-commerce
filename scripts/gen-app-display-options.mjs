// Copies every admin page's Display Options (sections / items the person can hide) from the website
// into the staff app: staff_app/lib/core/display_defs.dart. Run after changing a displayOptions file:
//   node scripts/gen-app-display-options.mjs
import fs from "fs";
import path from "path";
import { createRequire } from "module";
const require = createRequire(import.meta.url);
const ts = require("typescript");

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const files = [];
(function walk(d) {
  for (const f of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, f.name);
    if (f.isDirectory()) walk(p);
    else if (/\.(ts|tsx)$/.test(f.name) && /_PREF_KEY = /.test(fs.readFileSync(p, "utf8"))) files.push(p);
  }
})(path.join(root, "src/components/admin"));

const defs = {};
for (const file of files.sort()) {
  const src = fs.readFileSync(file, "utf8");
  const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, jsx: ts.JsxEmit.React } }).outputText;
  const mod = { exports: {} };
  try {
    new Function("module", "exports", "require", js)(mod, mod.exports, () => new Proxy({}, { get: () => () => null }));
  } catch (e) {
    console.warn("skip", path.relative(root, file), e.message);
    continue;
  }
  for (const [name, key] of Object.entries(mod.exports)) {
    if (!name.endsWith("_PREF_KEY") || typeof key !== "string") continue;
    const base = name.slice(0, -"_PREF_KEY".length);
    const groups = mod.exports[`${base}_GROUPS`] ?? [];
    const standalone = mod.exports[`${base}_STANDALONE`] ?? [];
    defs[key] = {
      groups: groups.map((g) => ({ group: g.group, label: g.groupLabel, items: (g.items ?? []).map((i) => [i.key, i.label]) })),
      standalone: standalone.map((i) => [i.key, i.label]),
    };
  }
}

const q = (s) => `'${String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\$/g, "\\$")}'`;
let out = `// GENERATED by scripts/gen-app-display-options.mjs from the website's displayOptions files — do not edit.
// Every admin page's "Display Options": the sections (with their parts) and single items a person can hide.
import '../ds/display_options.dart';

const displayDefs = <String, DisplayDef>{
`;
for (const [key, d] of Object.entries(defs)) {
  out += `  ${q(key)}: DisplayDef(${q(key)}, [\n`;
  for (const g of d.groups) out += `    DisplayGroup(${q(g.group)}, ${q(g.label)}, [${g.items.map(([k, l]) => `(${q(k)}, ${q(l)})`).join(", ")}]),\n`;
  out += `  ], [${d.standalone.map(([k, l]) => `(${q(k)}, ${q(l)})`).join(", ")}]),\n`;
}
out += "};\n";
fs.writeFileSync(path.join(root, "staff_app/lib/core/display_defs.dart"), out);
console.log(`${Object.keys(defs).length} pages → staff_app/lib/core/display_defs.dart`);
