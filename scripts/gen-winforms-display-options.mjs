// Copies every admin page's Display Options (sections, their parts, single items, parts hidden by default)
// from the website into the Windows software: winforms_app/Core/DisplayDefs.vb.
// Run after changing a displayOptions file on the website:  node scripts/gen-winforms-display-options.mjs
// Pages that exist only in the software (keys starting "app_") are kept from the current file.
import fs from "fs";
import path from "path";
import { createRequire } from "module";
const require = createRequire(import.meta.url);
const ts = require("typescript");

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const outFile = path.join(root, "winforms_app/Core/DisplayDefs.vb");
const files = [];
(function walk(d) {
  for (const f of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, f.name);
    if (f.isDirectory()) walk(p);
    else if (/\.(ts|tsx)$/.test(f.name) && /_PREF_KEY = /.test(fs.readFileSync(p, "utf8"))) files.push(p);
  }
})(path.join(root, "src/components/admin"));

const defs = {};
for (const file of files.sort()) {
  const src = fs.readFileSync(file, "utf8");
  const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, jsx: ts.JsxEmit.React } }).outputText;
  const mod = { exports: {} };
  try {
    new Function("module", "exports", "require", js)(mod, mod.exports, () => new Proxy({}, { get: () => () => null }));
  } catch (e) {
    console.warn("skip", path.relative(root, file), e.message);
    continue;
  }
  for (const [name, key] of Object.entries(mod.exports)) {
    if (!name.endsWith("_PREF_KEY") || typeof key !== "string") continue;
    const base = name.slice(0, -"_PREF_KEY".length);
    const groups = mod.exports[`${base}_GROUPS`] ?? [];
    const standalone = mod.exports[`${base}_STANDALONE`] ?? [];
    const hidden = mod.exports[`${base}_DEFAULT_HIDDEN`] ?? [];
    defs[key] = {
      groups: groups.map((g) => ({ group: g.group, label: g.groupLabel, items: (g.items ?? []).map((i) => [i.key, i.label]) })),
      standalone: standalone.map((i) => [i.key, i.label]),
      hidden: [...hidden],
    };
  }
}

// software-only pages: keep what the current file has for keys the website doesn't define
const keep = { groups: {}, singles: {} };
if (fs.existsSync(outFile)) {
  const cur = fs.readFileSync(outFile, "utf8");
  for (const m of cur.matchAll(/            Case "(app_[a-z0-9_]+)"\n                Return (\{[\s\S]*?\})\n(?=            Case)/g)) keep.groups[m[1]] = m[2];
  for (const m of cur.matchAll(/            Case "(app_[a-z0-9_]+)" : Return (\{.*\})\n/g)) keep.singles[m[1]] = m[2];
}

// VB treats curly quotes as string quotes too, so they go in as ChrW(…)
const q = (s) => `"${String(s).replace(/"/g, '""').replace(/[\u201C\u201D\u2018\u2019]/g, (c) => `" & ChrW(&H${c.charCodeAt(0).toString(16).toUpperCase()}) & "`)}"`;
let vb = `' GENERATED by scripts/gen-winforms-display-options.mjs from the website's displayOptions files — do not edit.
' Every admin page's "Display Options": the sections (with their parts) and single items a person can hide.
Public Module DisplayDefs
    ''' <summary>Parts hidden until someone turns them on (as on the website).</summary>
    Public ReadOnly DefaultHidden As New Dictionary(Of String, String()) From {
${Object.entries(defs).filter(([, d]) => d.hidden.length).map(([k, d]) => `        {${q(k)}, {${d.hidden.map(q).join(", ")}}}`).join(",\n")}}

    Public Function Groups(key As String) As DisplayGroup()
        Select Case key
`;
for (const [key, d] of Object.entries(defs)) {
  vb += `            Case ${q(key)}\n                Return {${d.groups.map((g) => `New DisplayGroup(${q(g.group)}, ${q(g.label)}${g.items.map(([k, l]) => `, ${q(`${k}|${l}`)}`).join("")})`).join(",\n                    ")}}\n`;
}
for (const [key, body] of Object.entries(keep.groups)) if (!defs[key]) vb += `            Case ${q(key)}\n                Return ${body}\n`;
vb += `            Case Else : Return {}
        End Select
    End Function

    Public Function Singles(key As String) As String()
        Select Case key
`;
for (const [key, d] of Object.entries(defs)) if (d.standalone.length) vb += `            Case ${q(key)} : Return {${d.standalone.map(([k, l]) => q(`${k}|${l}`)).join(", ")}}\n`;
for (const [key, body] of Object.entries(keep.singles)) if (!defs[key]) vb += `            Case ${q(key)} : Return ${body}\n`;
vb += `            Case Else : Return {}
        End Select
    End Function
End Module
`;
fs.writeFileSync(outFile, vb);
console.log(`${Object.keys(defs).length} website pages (+ ${Object.keys(keep.groups).length} software-only) → winforms_app/Core/DisplayDefs.vb`);
