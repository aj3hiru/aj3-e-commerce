// Generates winforms_app/Ui/IconData.vb: the SVG shapes of every lucide and Font Awesome (solid) icon the
// website uses (plus a few the Windows software needs), so the software draws the very same icons.
// Run after adding icons on the website:  node scripts/gen-winforms-icons.mjs
import fs from "fs";
import path from "path";
import { createRequire } from "module";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const require = createRequire(path.join(root, "package.json"));
const lucideDir = path.join(root, "node_modules/lucide-react/dist/esm/icons");
const kebab = (s) => s.replace(/Icon$/, "").replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Z])([A-Z][a-z])/g, "$1-$2").replace(/([a-zA-Z])([0-9])/g, "$1-$2").toLowerCase();

// every file of the website
const files = [];
(function walk(d) { for (const f of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, f.name); if (f.isDirectory()) walk(p); else if (/\.(tsx?|jsx?)$/.test(f.name)) files.push(p); } })(path.join(root, "src"));

const lucide = new Set(["sliders-horizontal", "chevron-down", "chevron-up", "chevron-left", "chevron-right", "x", "check", "search", "plus", "minus", "refresh-cw", "cloud", "cloud-off", "wifi-off", "log-out", "user", "menu", "printer", "download", "upload", "trash-2", "pencil", "eye", "eye-off", "calendar", "filter", "arrow-left", "more-vertical", "more-horizontal", "external-link", "copy", "info", "circle-alert", "circle-check", "triangle-alert", "loader", "moon", "sun", "bell", "phone", "message-circle", "map-pin", "navigation"]);
const fa = new Set(["faStar"]); // + icons the app draws that the website shows another way
for (const f of files) {
  const s = fs.readFileSync(f, "utf8");
  for (const m of s.matchAll(/import\s*(?:type\s*)?\{([^}]*)\}\s*from\s*["']lucide-react["']/g))
    for (let n of m[1].split(",")) { n = n.trim().split(/\s+as\s+/)[0].trim(); if (n && n !== "type" && !n.startsWith("type ") && n !== "LucideIcon" && n !== "LucideProps") lucide.add(kebab(n)); }
  for (const m of s.matchAll(/import\s*\{([^}]*)\}\s*from\s*["']@fortawesome\/free-solid-svg-icons["']/g))
    for (let n of m[1].split(",")) { n = n.trim().split(/\s+as\s+/)[0].trim(); if (n.startsWith("fa")) fa.add(n); }
}

// lucide-react's alias list: "export { default as AlertTriangle, … } from './icons/triangle-alert.mjs'"
const aliases = new Map();
for (const m of fs.readFileSync(path.join(root, "node_modules/lucide-react/dist/esm/lucide-react.mjs"), "utf8").matchAll(/export \{([^}]*)\} from '\.\/icons\/([a-z0-9-]+)\.mjs'/g))
  for (const part of m[1].split(",")) { const al = part.trim().split(/\s+as\s+/).pop(); if (al) aliases.set(kebab(al), `${m[2]}.mjs`); }
const aliasFile = (name) => aliases.get(name);

const out = [];
const missing = [];
const esc = (s) => s.replace(/"/g, '""');
for (const name of [...lucide].sort()) {
  // the icon's own file, or (old names like "alert-triangle") the file of its current name
  let arr = null;
  for (const f of [`${name}.mjs`, aliasFile(name)].filter(Boolean)) {
    const file = path.join(lucideDir, f);
    if (!fs.existsSync(file)) continue;
    arr = (await import(file)).__iconData?.node;
    if (arr) break;
  }
  if (!arr) { missing.push(name); continue; }
  const els = arr.map(([tag, a]) => {
    switch (tag) {
      case "path": return `path:${a.d}`;
      case "circle": return `circle:${a.cx} ${a.cy} ${a.r}`;
      case "ellipse": return `ellipse:${a.cx} ${a.cy} ${a.rx} ${a.ry}`;
      case "rect": return `rect:${a.x ?? 0} ${a.y ?? 0} ${a.width} ${a.height} ${a.rx ?? a.ry ?? 0}`;
      case "line": return `line:${a.x1} ${a.y1} ${a.x2} ${a.y2}`;
      case "polyline": case "polygon": return `${tag}:${a.points}`;
      default: return "";
    }
  }).filter(Boolean);
  out.push(`        {"${name}", "L|24|24|${esc(els.join(";"))}"}`);
}
const solid = require("@fortawesome/free-solid-svg-icons");
const seen = new Set();
for (const n of [...fa].sort()) {
  const ic = solid[n];
  if (!ic) { missing.push(n); continue; }
  if (seen.has(ic.iconName)) continue; // faPercent / faPercentage are the same icon
  seen.add(ic.iconName);
  const [w, h, , , d] = ic.icon;
  out.push(`        {"fa-${ic.iconName}", "F|${w}|${h}|${esc(Array.isArray(d) ? d.join(" ") : d)}"}`);
}
const vb = `' Generated by scripts/gen-winforms-icons.mjs — do not edit by hand.
' Icon shapes: lucide (ISC licence) and Font Awesome Free solid (CC BY 4.0), as used on the website.
Public Module IconData
    Public ReadOnly Svg As New Dictionary(Of String, String) From {
${out.join(",\n")}
    }
End Module
`;
fs.writeFileSync(path.join(root, "winforms_app/Ui/IconData.vb"), vb);
console.log(`icons: ${out.length} (lucide ${lucide.size}, fa ${fa.size}); missing: ${missing.join(", ") || "none"}`);
